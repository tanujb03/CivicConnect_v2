"""Run the AI evaluation harness and write reports.

    python -m ai.evaluation.run_eval --task intake --system local \
        --artifact ai/artifacts/civic_text_b0/<version> --name b0
    python -m ai.evaluation.run_eval --task fusion --fusion-weights ai/artifacts/fusion_calibrator/<version>
    python -m ai.evaluation.run_eval --task intake --system provider        # needs credentials

``--system provider|hybrid`` requires OPENAI_API_KEY and AI_INTAKE_MODEL. Without
them the run is reported as SKIPPED (exit code 2); no numbers are fabricated.
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

from ai.evaluation import eval_fusion, eval_intake
from ai.inference.config import ProviderSettings, load_taxonomy
from ai.inference.fusion.scoring import FusionWeights
from ai.inference.intake.service import IntakeService
from ai.inference.local.text_classifier import LocalTextClassifier
from ai.inference.providers.openai_provider import OpenAIProvider

HERE = Path(__file__).parent
DISCLAIMER = ("SYNTHETIC EVALUATION. Held-out template families and place names, but generated by the same "
              "process as the training data. These numbers are a regression/ablation signal, NOT an estimate of "
              "real-world accuracy.")


def read_jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as fh:
        return [json.loads(l) for l in fh if l.strip()]


def _sha(path: Path) -> str:
    import hashlib
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_report(out_dir: Path, name: str, payload: dict) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    payload = {"disclaimer": DISCLAIMER, "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), **payload}
    jp = out_dir / f"{name}.json"
    jp.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out_dir / f"{name}.md").write_text(render_md(name, payload), encoding="utf-8")
    return jp


def render_md(name: str, p: dict) -> str:
    r = p["results"]
    lines = [f"# Evaluation report — {name}", "", f"> **{p['disclaimer']}**", "",
             f"- Task: `{r['task']}`  |  System: `{p.get('system')}`  |  Created: {p['created_at']}",
             f"- Dataset: `{p['dataset']['file']}` sha256 `{p['dataset']['sha256'][:16]}…` ({r.get('n', r.get('n_pairs'))} items)",
             f"- Artifact: `{p.get('artifact')}`", ""]
    if r["task"] == "intake":
        lines += ["## Headline", "", "| metric | value |", "|---|---|"]
        for k in ("category_accuracy", "subcategory_accuracy", "subcategory_macro_f1", "routing_accuracy_department",
                  "calibration_ece_category", "coverage_at_threshold", "category_accuracy_when_accepted",
                  "structured_output_validity", "degraded_rate", "severity_agreement"):
            lines.append(f"| {k} | {r[k]} |")
        lines += ["", f"95% CI for subcategory accuracy: {r['subcategory_accuracy_ci95']}", "", f"_{r['severity_note']}_", "",
                  "## By language", "", "| language | n | subcategory acc | category acc |", "|---|---|---|---|"]
        for k, v in r["by_language"].items():
            lines.append(f"| {k} | {v['n']} | {v['subcategory_accuracy']} | {v['category_accuracy']} |")
        lines += ["", "## Code-mixed / noisy", "", "| slice | n | subcategory acc |", "|---|---|---|"]
        for grp in ("by_code_mixed", "by_noisy"):
            for k, v in r[grp].items():
                lines.append(f"| {grp[3:]}={k} | {v['n']} | {v['subcategory_accuracy']} |")
        lines += ["", "## Top confusions", ""] + [f"- {c['true']} → {c['pred']} ×{c['count']}" for c in r["top_confusions"]]
    else:
        lines += ["## Headline", "", "```json", json.dumps({k: v for k, v in r.items() if k != "by_pair_type"}, indent=2), "```",
                  "", "## By pair type", "", "| type | n | mean score | flagged duplicate |", "|---|---|---|---|"]
        for k, v in r["by_pair_type"].items():
            lines.append(f"| {k} | {v['n']} | {v['mean_score']} | {v['flagged_possible_duplicate']} |")
    lines += ["", "## Limitations", "- Synthetic data; Hindi/Marathi text unreviewed by native speakers.",
              "- Single held-out family per class/language: wide confidence intervals; use k-fold (`--test-fold`) for variance.", ""]
    return "\n".join(lines)


def build_intake_system(system: str, artifact: Path | None):
    clf = LocalTextClassifier.load(artifact) if artifact else None
    provider = None
    if system in ("provider", "hybrid"):
        s = ProviderSettings.from_env()
        if s.api_key is None or not s.model_for("intake"):
            return None, clf, "requires OPENAI_API_KEY and AI_INTAKE_MODEL"
        provider = OpenAIProvider(s)
    if system == "local" and clf is None:
        return None, clf, "--artifact is required for --system local"
    use_clf = clf if system in ("local", "hybrid") else None
    return IntakeService(provider=provider, classifier=use_clf), clf, None


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--task", choices=["intake", "fusion"], required=True)
    ap.add_argument("--system", choices=["local", "provider", "hybrid"], default="local")
    ap.add_argument("--artifact", type=Path, default=None, help="B0 classifier artifact dir")
    ap.add_argument("--fusion-weights", type=Path, default=None, help="weights fitted on the lexical semantic signal")
    ap.add_argument("--eval-dir", type=Path, default=HERE / "datasets")
    ap.add_argument("--out", type=Path, default=HERE / "reports")
    ap.add_argument("--name", default=None)
    a = ap.parse_args(argv)

    if a.task == "intake":
        ds = a.eval_dir / "intake_eval.v1.jsonl"
        svc, clf, why = build_intake_system(a.system, a.artifact)
        if svc is None:
            print(f"SKIPPED: {why}. No report written.", file=sys.stderr)
            return 2
        results = eval_intake.evaluate(svc, read_jsonl(ds))
        art = f"{clf.model_name}@{clf.model_version}" if clf else None
        name = a.name or f"intake_{a.system}"
    else:
        ds = a.eval_dir / "fusion_eval_pairs.v1.jsonl"
        w = FusionWeights.load(a.fusion_weights) if a.fusion_weights else None
        results = eval_fusion.evaluate(read_jsonl(ds), w)
        art = f"fusion_weights@{w.version}" if w else "uncalibrated_prior"
        name = a.name or "fusion_lexical"
    path = write_report(a.out, name, {"system": a.system if a.task == "intake" else "lexical", "artifact": art,
                                      "dataset": {"file": ds.name, "sha256": _sha(ds)},
                                      "taxonomy_version": load_taxonomy().version, "results": results})
    print(f"report: {path}")
    print(json.dumps({k: v for k, v in results.items() if not isinstance(v, (dict, list))}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
