"""Explicit manifest: dataset -> task -> allowed fields -> labels -> taxonomy mapping -> evaluation track.

BMC rows are DERIVED from the column-role policy (single source of truth); other rows are declared here. The
committed ``TASK_MATRIX.md`` / ``task_matrix.v1.json`` / ``BMC_COLUMN_POLICY.md`` are generated by this module
(``python -m ai.training.src.data_sources.task_matrix --write``) and a test fails if they drift.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from .card_schema import list_cards, load_card
from .column_roles import TaskPolicy
from .mapping import MappingTable

