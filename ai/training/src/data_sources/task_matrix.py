IMG_FORBIDDEN = ["bounding boxes / annotation files", "file or directory names that encode the class", "group id (used only to build splits)"]


def _map_ref(mapping_id: str | None) -> str:
    if not mapping_id:
        return "—"
    try:
        t = MappingTable.load(mapping_id)
        return f"`{t.mapping_id}@{t.version}` ({t.raw['status']})"
    except Exception:
        return f"`{mapping_id}`"


