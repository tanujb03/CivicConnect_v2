def _bmc_rows(policy: TaskPolicy) -> list[dict]:
    mref = f"{_map_ref('bmc_mumbai_to_civic')}; departments {_map_ref('bmc_mumbai_departments')}"
    out = []
    for t in policy.spec.tasks:
        forb = sorted(policy.effective_forbidden(t.task) - {r.name for r in policy.roles.values() if r.phase in ("sensitive_attribute", "pii_never_read")})
        out.append({"source_id": "bmc_mumbai", "task": t.task, "capability": t.capability, "status": t.status, "inputs": t.inputs, "targets": t.targets,
                    "forbidden": forb + ["every unclassified column", "complainant_profile (sensitive)", "pii (never read)"], "labels": "13 reported complaint categories + departments (unverified)",
                    "taxonomy_mapping": mref, "track": t.track, "implemented_in_eval_harness": t.task in {"taxonomy_coverage", "routing_agreement", "triage_priority_prior", "resolution_time_prior", "recurrence_hotspot"},
                    "requires": t.requires, "requires_any": t.requires_any, "operator_confirmations": t.operator_confirmations, "conditions": t.conditions, "notes": t.notes})
    return out


def build_matrix() -> list[dict]:
    policy = TaskPolicy.load("bmc_mumbai")
    rows = _static() + _bmc_rows(policy)
    order = {c.id: i for i, c in enumerate(sorted(list_cards(), key=lambda c: ({"primary": 0, "secondary": 1, "optional": 2, "future": 3}[c.priority], c.id)))}
    rows.sort(key=lambda r: (order[r["source_id"]], r["task"]))
    for r in rows:
        r["source_priority"] = load_card(r["source_id"]).priority
    return rows


def _cell(x) -> str:
    if isinstance(x, list):
        return ", ".join(f"`{i}`" for i in x) if x else "—"
    return str(x) if x not in (None, "") else "—"


def render_markdown() -> str:
    rows = build_matrix()
    L = ["# Dataset → task → allowed fields → labels → taxonomy mapping → evaluation track", "",
         "> GENERATED by `ai/training/src/data_sources/task_matrix.py` (`--write`); do not edit by hand. BMC rows are derived from `mappings/bmc_mumbai_columns.v1.json`.",
         "> Every licence is UNVERIFIED and no real dataset has been downloaded or profiled. Statuses describe what each dataset COULD legitimately support, not results.", "",
         "Status: `supported` · `conditional` (needs the stated columns/confirmations) · `demo_only` · `unsupported` / `not_pursued` / `not_available` · `future`. "
         "Tracks: `synthetic`, `real_holdout`, `hybrid`, `descriptive`, `none`. **Synthetic and real metrics are never pooled.**", ""]
    cur, notes = None, []

    def flush():
        if notes:
            L.extend([""] + [f"- `{t}`: {n}" for t, n in notes])
            notes.clear()

    for r in rows:
        if r["source_id"] != cur:
            flush()
            cur = r["source_id"]
            c = load_card(cur)
            L += ["", f"## {c.name}", f"`{cur}` · priority **{c.priority}** · licence **{c.license.status}** · origin **{c.origin_status}** · identity **{c.identity_status}**", "",
                  "| task | capability | status | allowed inputs | targets | forbidden | labels | taxonomy mapping | track | in eval harness |", "|---|---|---|---|---|---|---|---|---|---|"]
        L.append(f"| `{r['task']}` | {r['capability']} | {r['status']} | {_cell(r['inputs'])} | {_cell(r['targets'])} | {_cell(r['forbidden'])} | {r['labels']} | {r['taxonomy_mapping']} | "
                 f"{r['track']} | {'yes' if r['implemented_in_eval_harness'] else 'no'} |")
        extra = []
        if r.get("requires") or r.get("requires_any"):
            extra.append(f"requires {_cell(r.get('requires', []) + r.get('requires_any', []))}")
        if r.get("operator_confirmations"):
            extra.append(f"operator must confirm {_cell(r['operator_confirmations'])}")
        extra += r.get("conditions", [])
        if r.get("notes"):
            extra.append(r["notes"])
        if extra:
            notes.append((r["task"], "; ".join(extra)))
    flush()
    L.append("")
    return "\n".join(L)


def render_bmc_policy_markdown() -> str:
    p = TaskPolicy.load("bmc_mumbai")
    L = ["# BMC Mumbai column policy (default-deny)", "",
         "> GENERATED from `mappings/bmc_mumbai_columns.v1.json`. Column NAMES are expectations: the Kaggle page/data dictionary were unreachable. Roles are assigned by alias or by an explicit `--role-map`; "
         "every column no role claims is **unclassified and unavailable to every task**. Not an official BMC source; origin and licence unverified.", "",
         "## Roles and phases", "", "| role | phase | stored in prepared output | note |", "|---|---|---|---|"]
    for r in p.spec.roles:
        L.append(f"| `{r.name}` | {r.phase} | {'yes' if r.store and r.phase not in ('sensitive_attribute', 'pii_never_read') else 'NO'} | {r.description or ''} |")
    L += ["", "Phases: `identifier`/`at_submission` (known when filed) < `post_triage` (assigned after triage) < `post_resolution` (outcomes/events after work starts). "
          "`sensitive_attribute` and `pii_never_read` roles are never read, stored, input or target.", "", "## Per-task permissions", ""]
    for t in p.spec.tasks:
        ins, tgts = p.allowed_roles(t.task)
        L += [f"### `{t.task}` — {t.status} ({t.capability}; track `{t.track}`; max input phase `{t.max_phase}`)", "",
              f"- **allowed inputs:** {_cell(ins)}", f"- **targets:** {_cell(tgts)}", f"- **forbidden (explicit):** {_cell([f for f in t.forbidden])} (+ all sensitive/PII roles)",
              f"- **requires:** {_cell(t.requires + t.requires_any)}" + (f"; operator confirms {_cell(t.operator_confirmations)}" if t.operator_confirmations else ""),
              f"- **leakage checks:** {_cell(t.leakage_checks)}"] + [f"- condition: {c}" for c in t.conditions] + ([f"- {t.notes}"] if t.notes else []) + [""]
    return "\n".join(L)


def write_all() -> None:
    (HERE / "TASK_MATRIX.md").write_text(render_markdown(), encoding="utf-8")
    (HERE / "BMC_COLUMN_POLICY.md").write_text(render_bmc_policy_markdown(), encoding="utf-8")
    (HERE / "task_matrix.v1.json").write_text(json.dumps(build_matrix(), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    if "--write" in sys.argv:
        write_all()
        print("wrote TASK_MATRIX.md, BMC_COLUMN_POLICY.md, task_matrix.v1.json")
    else:
        print(render_markdown())
